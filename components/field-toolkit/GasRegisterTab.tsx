'use client';

import { useEffect, useMemo, useState } from 'react';
import { AlertTriangle, CheckCircle2, Download, History, PlusCircle, RefreshCw, Save, ShieldCheck, Trash2, WifiOff } from 'lucide-react';
import { useAuth } from '@/lib/auth';
import { searchRefrigerantsOnce, useApprovedSuppliers, useGasLogs, usePlannerJobs } from '@/lib/api';
import { useGasLogQueue } from '@/lib/gas-log-queue';
import { RefrigerantAutocomplete, refrigerantLabel } from '@/components/RefrigerantAutocomplete';
import { JobTypeLabels, type JobType, type Refrigerant, type RefrigerantLog } from '@/types/index';
import { JOB_TYPE_OPTIONS } from './checklists';

const inputClass = 'min-h-11 w-full border border-stone-200 bg-white px-3 py-2 text-sm outline-none transition focus:border-[#D97706] focus:ring-2 focus:ring-[#D97706]/20';
export const ACTIONS = ['Charge', 'Recovery', 'Leak Repair'] as const;
export type Action = (typeof ACTIONS)[number];
type LogState = 'synced' | 'pending' | 'failed';

const EMPTY_FORM = {
  clientName: '',
  location: '',
  jobType: 'COLD_ROOM' as JobType,
  refrigerant: null as Refrigerant | null,
  refrigerantType: '',
  amount: '',
  actionType: 'Charge' as Action,
  approvedSupplierId: '',
  pesepayTransactionId: '',
  plannerJobId: '',
};

function Field({ label, htmlFor, hint, children }: { label: string; htmlFor?: string; hint?: string; children: React.ReactNode }) {
  return (
    <div className="space-y-1.5">
      <label htmlFor={htmlFor} className="block text-sm font-semibold text-stone-700">
        {label}
        {hint && <span className="ml-2 text-xs font-medium text-stone-500">{hint}</span>}
      </label>
      {children}
    </div>
  );
}

async function downloadPdf(log: RefrigerantLog) {
  const { jsPDF } = await import('jspdf');
  const doc = new jsPDF();
  doc.setFontSize(22);
  doc.text('COOLPRO Field Service Log', 20, 20);
  doc.setFontSize(12);
  doc.text(`Log ID: ${log.id}`, 20, 30);
  doc.text(`Date: ${new Date(log.timestamp).toLocaleString()}`, 20, 40);
  doc.setFontSize(16);
  doc.text('Technician Information', 20, 60);
  doc.setFontSize(12);
  doc.text(`Name: ${log.technicianName}`, 20, 70);
  doc.text(`ID: ${log.technicianId}`, 20, 80);
  doc.setFontSize(16);
  doc.text('Service Details', 20, 100);
  doc.setFontSize(12);
  doc.text(`Client: ${log.clientName}`, 20, 110);
  doc.text(`Location: ${log.location}`, 20, 120);
  doc.text(`Job Type: ${JobTypeLabels[log.jobType] || log.jobType}`, 20, 130);
  doc.text(`Action: ${log.actionType}`, 20, 140);
  doc.text(`Refrigerant: ${log.refrigerantType}`, 20, 150);
  doc.text(`Amount: ${log.amount} kg`, 20, 160);
  doc.text(`Approved Supplier: ${log.approvedSupplierName || 'Unverified / not selected'}`, 20, 170);
  doc.text(`Pesepay Transaction ID: ${log.pesepayTransactionId || 'Not provided'}`, 20, 180);
  doc.setFontSize(10);
  doc.text('Generated by COOLPRO Digital Toolkit', 20, 270);
  doc.save(`coolpro-log-${log.id}.pdf`);
}

export interface GasRegisterPrefill {
  /** Refrigerant code, from the nameplate scanner or a voice command. */
  code?: string;
  amount?: string;
  action?: Action;
  client?: string;
  source: 'scan' | 'voice';
}

interface GasRegisterTabProps {
  prefill?: GasRegisterPrefill;
  onPrefillConsumed?: () => void;
}

export default function GasRegisterTab({ prefill, onPrefillConsumed }: GasRegisterTabProps) {
  const { user } = useAuth();
  const { data: suppliers = [], error: suppliersError, isLoading: suppliersLoading } = useApprovedSuppliers();
  const { data: plannerJobs = [] } = usePlannerJobs();
  const { data: savedLogs = [] } = useGasLogs(undefined, undefined, 50);
  const { queue, failed, isOnline, syncing, submit, retry, retryFailed, discard } = useGasLogQueue(user?.id);

  const [form, setForm] = useState(EMPTY_FORM);
  const [errors, setErrors] = useState<Record<string, string>>({});
  const [notice, setNotice] = useState('');
  const [prefillNotice, setPrefillNotice] = useState('');

  const openJobs = useMemo(() => plannerJobs.filter(job => job.status !== 'completed' && job.status !== 'cancelled'), [plannerJobs]);

  // Apply details from a nameplate scan or a voice command. Nothing is saved: the person reviews and presses Save.
  const prefillKey = prefill ? JSON.stringify(prefill) : '';
  useEffect(() => {
    if (!prefill) return;
    let cancelled = false;
    (async () => {
      let refrigerant: Refrigerant | null = null;
      if (prefill.code) {
        try {
          refrigerant = (await searchRefrigerantsOnce({ q: prefill.code, pageSize: 1 })).data[0] ?? null;
        } catch (err) {
          console.error('Could not look up the refrigerant:', err);
        }
      }
      if (cancelled) return;
      setForm(prev => ({
        ...prev,
        ...(prefill.code ? { refrigerant, refrigerantType: refrigerant ? refrigerantLabel(refrigerant) : prefill.code } : {}),
        ...(prefill.amount ? { amount: prefill.amount } : {}),
        ...(prefill.action ? { actionType: prefill.action } : {}),
        ...(prefill.client ? { clientName: prefill.client } : {}),
      }));
      setPrefillNotice(prefill.source === 'voice' ? 'Filled from your voice command. Check every field, then press Save.' : `Filled from nameplate scan: ${prefill.code}`);
      onPrefillConsumed?.();
    })();
    return () => { cancelled = true; };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [prefillKey]);

  const chooseJob = (jobId: string) => {
    const job = openJobs.find(item => item.id === jobId);
    setForm(prev => ({
      ...prev,
      plannerJobId: jobId,
      // Fill the obvious details from the job, without overwriting what the person already typed.
      clientName: prev.clientName || job?.clientName || '',
      location: prev.location || job?.location || '',
      jobType: job ? job.jobType : prev.jobType,
    }));
  };

  // One list: what is on the server, plus anything still waiting on this device.
  const history = useMemo(() => {
    const byId = new Map<string, { log: RefrigerantLog; state: LogState; reason?: string }>();
    for (const log of savedLogs) byId.set(log.id, { log, state: 'synced' });
    for (const log of queue) byId.set(log.id, { log, state: failed[log.id] ? 'failed' : 'pending', reason: failed[log.id] });
    return [...byId.values()].sort((a, b) => new Date(b.log.timestamp).getTime() - new Date(a.log.timestamp).getTime());
  }, [savedLogs, queue, failed]);

  const pendingCount = queue.filter(log => !failed[log.id]).length;
  const failedLogs = queue.filter(log => failed[log.id]);

  const validate = () => {
    const next: Record<string, string> = {};
    if (!form.clientName.trim()) next.clientName = 'Enter the client name.';
    if (!form.refrigerantType.trim()) next.refrigerant = 'Choose the refrigerant.';
    const amount = Number(form.amount);
    if (!form.amount.trim() || !Number.isFinite(amount) || amount <= 0) next.amount = 'Enter a weight greater than zero.';
    else if (amount > 10000) next.amount = 'That is more than 10,000 kg. Check the figure.';
    return next;
  };

  const handleSubmit = (event: React.FormEvent) => {
    event.preventDefault();
    const found = validate();
    setErrors(found);
    if (Object.keys(found).length > 0) return;

    const supplier = suppliers.find(item => item.id === form.approvedSupplierId);
    const log: RefrigerantLog = {
      id: crypto.randomUUID(),
      technicianId: user?.id || 'unknown',
      technicianName: user?.name || 'Anonymous',
      clientName: form.clientName.trim(),
      location: form.location.trim(),
      plannerJobId: form.plannerJobId || undefined,
      jobType: form.jobType,
      refrigerantId: form.refrigerant?.id,
      refrigerantType: form.refrigerantType,
      amount: Number(form.amount),
      actionType: form.actionType,
      approvedSupplierId: supplier?.id,
      approvedSupplierName: supplier?.name,
      supplierVerified: Boolean(supplier),
      pesepayTransactionId: form.pesepayTransactionId.trim() || undefined,
      timestamp: new Date().toISOString(),
    };
    submit(log);
    setForm(EMPTY_FORM);
    setPrefillNotice('');
    setNotice(isOnline ? 'Saved. Syncing to the central database.' : 'Saved on this device. It will sync when you are back online.');
  };

  return (
    <div className="space-y-6">
      <div className="flex items-start gap-3 border border-amber-200 bg-amber-50 p-4">
        <ShieldCheck className="mt-0.5 h-5 w-5 shrink-0 text-amber-600" aria-hidden="true" />
        <div>
          <p className="text-sm font-semibold text-amber-800">Compliance notice</p>
          <p className="mt-1 text-xs text-amber-700">COOLPRO supports only refrigerants compliant with SI 49 of 2023 and the Kigali Amendment. Only R-290, R-744 (CO₂), and R-32 are permitted for new entries.</p>
        </div>
      </div>

      <SyncBanner isOnline={isOnline} syncing={syncing} pending={pendingCount} failedCount={failedLogs.length} onRetry={retry} />

      <form onSubmit={handleSubmit} noValidate className="space-y-5 border border-stone-200 bg-stone-50/60 p-4 sm:p-6" aria-label="New log entry">
        <h3 className="flex items-center gap-2 font-semibold text-[#b45309]"><PlusCircle className="h-5 w-5" aria-hidden="true" />New log entry</h3>

        <fieldset>
          <legend className="mb-2 text-sm font-semibold text-stone-700">What did you do?</legend>
          <div className="grid grid-cols-3 gap-2 sm:gap-3">
            {ACTIONS.map(action => (
              <button
                key={action}
                type="button"
                onClick={() => setForm({ ...form, actionType: action })}
                aria-pressed={form.actionType === action}
                className={`min-h-12 border px-2 py-2 text-sm font-semibold transition ${form.actionType === action ? 'border-[#D97706] bg-[#D97706] text-white' : 'border-stone-200 bg-white text-stone-700 hover:border-[#D97706]'}`}
              >
                {action}
              </button>
            ))}
          </div>
        </fieldset>

        <div className="grid grid-cols-1 gap-4 md:grid-cols-2">
          <Field label="Planner job" hint="Optional. Fills in client and site" htmlFor="log-job">
            <select id="log-job" value={form.plannerJobId} onChange={e => chooseJob(e.target.value)} className={inputClass}>
              <option value="">Not linked to a job</option>
              {openJobs.map(job => <option key={job.id} value={job.id}>{job.clientName}, {job.scheduledDate}</option>)}
            </select>
          </Field>
          <Field label="Job type" htmlFor="log-type">
            <select id="log-type" value={form.jobType} onChange={e => setForm({ ...form, jobType: e.target.value as JobType })} className={inputClass}>
              {JOB_TYPE_OPTIONS.map(option => <option key={option.value} value={option.value}>{option.label}</option>)}
            </select>
          </Field>
          <Field label="Client name" htmlFor="log-client">
            <input id="log-client" value={form.clientName} onChange={e => setForm({ ...form, clientName: e.target.value })} aria-invalid={Boolean(errors.clientName)} className={inputClass} placeholder="Shoprite Bulawayo" />
            {errors.clientName && <p role="alert" className="text-xs text-rose-700">{errors.clientName}</p>}
          </Field>
          <Field label="Work location" htmlFor="log-location">
            <input id="log-location" value={form.location} onChange={e => setForm({ ...form, location: e.target.value })} className={inputClass} placeholder="Unit 3 roof, aisle 4 freezer" />
          </Field>
          <Field label="Refrigerant">
            <RefrigerantAutocomplete
              value={form.refrigerant}
              onSelect={refrigerant => {
                setForm({ ...form, refrigerant, refrigerantType: refrigerant ? refrigerantLabel(refrigerant) : '' });
                setPrefillNotice('');
              }}
            />
            {errors.refrigerant && <p role="alert" className="text-xs text-rose-700">{errors.refrigerant}</p>}
            {prefillNotice && <p className="text-xs font-medium text-emerald-700">{prefillNotice}</p>}
          </Field>
          <Field label="Amount (kg)" htmlFor="log-amount">
            <input id="log-amount" type="number" inputMode="decimal" min="0" step="0.001" value={form.amount} onChange={e => setForm({ ...form, amount: e.target.value })} aria-invalid={Boolean(errors.amount)} className={inputClass} placeholder="0.00" />
            {errors.amount && <p role="alert" className="text-xs text-rose-700">{errors.amount}</p>}
          </Field>
          <Field label="Approved supplier" htmlFor="log-supplier">
            <select id="log-supplier" value={form.approvedSupplierId} onChange={e => setForm({ ...form, approvedSupplierId: e.target.value })} disabled={suppliersLoading} className={`${inputClass} disabled:bg-stone-100 disabled:text-stone-400`}>
              <option value="">{suppliersLoading ? 'Loading suppliers…' : 'No approved supplier'}</option>
              {suppliers.map(supplier => <option key={supplier.id} value={supplier.id}>{supplier.name}</option>)}
            </select>
            {suppliersError && <p className="text-xs text-rose-700">Could not load approved suppliers. Check your connection.</p>}
          </Field>
          <Field label="Pesepay transaction ID" hint="Needed for rewards" htmlFor="log-pesepay">
            <input id="log-pesepay" value={form.pesepayTransactionId} onChange={e => setForm({ ...form, pesepayTransactionId: e.target.value })} className={inputClass} placeholder="REC-20260331-001" />
          </Field>
        </div>

        {!form.approvedSupplierId && (
          <p className="border border-amber-200 bg-amber-50 px-4 py-3 text-sm text-amber-800">Purchases from unapproved suppliers are not eligible for rewards points and are flagged in the NOU compliance report.</p>
        )}

        <div className="space-y-2">
          <button type="submit" className="flex min-h-12 w-full items-center justify-center gap-2 bg-[#D97706] px-6 py-3 font-semibold text-white shadow-lg shadow-[#D97706]/20 transition hover:bg-[#b45309]">
            <Save className="h-5 w-5" aria-hidden="true" />
            Save log entry
          </button>
          {notice && <p role="status" className="text-sm font-medium text-emerald-700">{notice}</p>}
        </div>
      </form>

      {failedLogs.length > 0 && (
        <section aria-label="Logs the server refused" className="space-y-2 border border-rose-200 bg-rose-50 p-4">
          <p className="flex items-center gap-2 text-sm font-semibold text-rose-800"><AlertTriangle className="h-4 w-4" aria-hidden="true" />{failedLogs.length} log{failedLogs.length === 1 ? ' was' : 's were'} refused by the server</p>
          <ul className="space-y-2">
            {failedLogs.map(log => (
              <li key={log.id} className="flex flex-col gap-2 bg-white p-3 text-sm sm:flex-row sm:items-center sm:justify-between">
                <span><strong>{log.clientName}</strong>, {log.amount} kg {log.refrigerantType}. <span className="text-rose-700">{failed[log.id]}</span></span>
                <span className="flex shrink-0 gap-2">
                  <button type="button" onClick={() => retryFailed(log.id)} className="border border-stone-200 px-3 py-1.5 text-xs font-semibold text-stone-700 hover:bg-stone-50">Try again</button>
                  <button type="button" onClick={() => discard(log.id)} className="inline-flex items-center gap-1 border border-rose-200 px-3 py-1.5 text-xs font-semibold text-rose-700 hover:bg-rose-100"><Trash2 className="h-3.5 w-3.5" aria-hidden="true" />Remove</button>
                </span>
              </li>
            ))}
          </ul>
        </section>
      )}

      <section className="space-y-3" aria-label="Recent activity">
        <h3 className="flex items-center gap-2 font-bold text-stone-900"><History className="h-5 w-5 text-stone-500" aria-hidden="true" />Recent activity{user ? <span className="font-medium text-[#b45309]"> for {user.name}</span> : null}</h3>
        {history.length === 0 ? (
          <div className="border border-dashed border-stone-300 bg-stone-50 py-10 text-center text-sm font-medium text-stone-600">No logs recorded yet.</div>
        ) : (
          <ul className="space-y-3">
            {history.map(({ log, state }) => (
              <li key={log.id} className="border border-stone-200 bg-white p-4">
                <div className="flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
                  <div className="min-w-0 space-y-1">
                    <div className="flex flex-wrap items-center gap-2">
                      <span className={`rounded-full px-2 py-0.5 text-[10px] font-bold uppercase tracking-wider ${log.actionType === 'Recovery' ? 'bg-amber-100 text-amber-700' : log.actionType === 'Leak Repair' ? 'bg-red-100 text-red-700' : 'bg-green-100 text-green-700'}`}>{log.actionType}</span>
                      <SyncChip state={state} />
                      <span className="text-xs text-stone-500">{new Date(log.timestamp).toLocaleDateString('en-ZW')} {new Date(log.timestamp).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })}</span>
                    </div>
                    <h4 className="truncate font-bold text-stone-900">{log.clientName}</h4>
                    <p className="text-sm text-stone-600"><span className="font-medium text-stone-800">{log.amount} kg</span> of {log.refrigerantType}{log.location ? ` · ${log.location}` : ''} · {JobTypeLabels[log.jobType] || log.jobType}</p>
                    <p className="text-xs text-stone-500">
                      {log.supplierVerified ? 'Supplier verified' : 'Supplier unverified'}{log.approvedSupplierName ? `: ${log.approvedSupplierName}` : ''}{log.pesepayTransactionId ? ` · ${log.pesepayTransactionId}` : ''}
                    </p>
                  </div>
                  <button type="button" onClick={() => void downloadPdf(log)} className="inline-flex min-h-11 shrink-0 items-center justify-center gap-2 border border-stone-200 bg-stone-50 px-4 py-2 text-sm font-semibold text-stone-700 transition hover:bg-stone-100">
                    <Download className="h-4 w-4" aria-hidden="true" />
                    PDF
                  </button>
                </div>
              </li>
            ))}
          </ul>
        )}
      </section>
    </div>
  );
}

function SyncChip({ state }: { state: LogState }) {
  const map = {
    synced: { label: 'Synced', className: 'bg-emerald-50 text-emerald-700' },
    pending: { label: 'On this device', className: 'bg-amber-50 text-amber-700' },
    failed: { label: 'Refused', className: 'bg-rose-50 text-rose-700' },
  } as const;
  return <span className={`rounded-full px-2 py-0.5 text-[10px] font-semibold ${map[state].className}`}>{map[state].label}</span>;
}

function SyncBanner({ isOnline, syncing, pending, failedCount, onRetry }: { isOnline: boolean; syncing: boolean; pending: number; failedCount: number; onRetry: () => void }) {
  if (!isOnline) {
    return (
      <div role="status" className="flex items-start gap-3 border border-amber-200 bg-amber-50 p-4">
        <WifiOff className="mt-0.5 h-5 w-5 text-amber-600" aria-hidden="true" />
        <div>
          <p className="text-sm font-bold text-amber-900">You are offline</p>
          <p className="mt-1 text-xs text-amber-700">{pending > 0 ? `${pending} log${pending === 1 ? '' : 's'} saved on this device. They sync automatically when you are back online.` : 'New logs are saved on this device and sync when you are back online.'}</p>
        </div>
      </div>
    );
  }
  if (pending > 0) {
    return (
      <div role="status" className="flex flex-col gap-3 border border-amber-200 bg-amber-50 p-4 sm:flex-row sm:items-center sm:justify-between">
        <div className="flex items-start gap-3">
          <RefreshCw className={`mt-0.5 h-5 w-5 text-amber-600 ${syncing ? 'animate-spin' : ''}`} aria-hidden="true" />
          <div>
            <p className="text-sm font-bold text-amber-900">{syncing ? 'Syncing…' : `${pending} log${pending === 1 ? '' : 's'} waiting to sync`}</p>
            <p className="mt-1 text-xs text-amber-700">Saved on this device, not yet on the central database.</p>
          </div>
        </div>
        {!syncing && <button type="button" onClick={onRetry} className="inline-flex min-h-11 shrink-0 items-center gap-2 bg-[#D97706] px-4 py-2 text-sm font-semibold text-white hover:bg-[#b45309]"><RefreshCw className="h-4 w-4" aria-hidden="true" />Sync now</button>}
      </div>
    );
  }
  if (failedCount > 0) return null;
  return (
    <div role="status" className="flex items-center gap-3 border border-emerald-200 bg-emerald-50 p-3">
      <CheckCircle2 className="h-5 w-5 text-emerald-600" aria-hidden="true" />
      <p className="text-sm font-medium text-emerald-800">All logs are synced to the central database.</p>
    </div>
  );
}

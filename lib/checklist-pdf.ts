import type { jsPDF } from 'jspdf';
import type { CellHookData } from 'jspdf-autotable';
import type { InstallationChecklistSnapshot } from '@/types/index';
import {
  BRAND,
  drawAmberNote,
  drawFooters,
  drawIdentityStrip,
  drawKeyTable,
  drawSignatures,
  formatDate,
  formatWhen,
  loadLogo,
  newDocument,
  sectionHeading,
  type AutoTable,
  type DocWithTable,
} from '@/lib/pdf-brand';

export interface ChecklistPdfAuthor {
  technicianName: string;
  technicianId?: string | null;
}

const TITLES: Record<InstallationChecklistSnapshot['checklistType'], string> = {
  installation: 'New installation verification checklist',
  regassing: 'Regassing and service checklist',
};

/**
 * A branded record of a saved checklist: headline result, every line with its compliance source,
 * and the signature block that goes on the site file.
 */
export async function downloadChecklistPdf(snapshot: InstallationChecklistSnapshot, author: ChecklistPdfAuthor) {
  const [{ jsPDF: JsPdf }, { default: autoTable }, logo] = await Promise.all([
    import('jspdf'),
    import('jspdf-autotable'),
    loadLogo(),
  ]);

  const percent = snapshot.totalItems === 0 ? 0 : Math.round((snapshot.completedItems / snapshot.totalItems) * 100);
  const complete = snapshot.completedItems === snapshot.totalItems;
  const title = TITLES[snapshot.checklistType];

  const doc = newDocument(JsPdf, {
    title: `HEVACRAZ ${title}`,
    subject: title,
    kicker: 'Field Service Log · Compliance checklist',
  }, logo, {
    label: 'CHECKLIST',
    value: snapshot.checklistType.toUpperCase(),
    lines: [formatDate(snapshot.completedAt), `Version ${snapshot.version ?? 'unversioned'}`],
  });

  let y = drawIdentityStrip(doc, 46, [
    { label: 'CHECKLIST', value: title, x: 20, maxWidth: 92 },
    { label: 'COMPLETED', value: `${snapshot.completedItems} of ${snapshot.totalItems}`, detail: `${percent}% of the listed items`, x: 120 },
    { label: 'RESULT', value: complete ? 'Complete' : 'Outstanding', x: 158 },
  ]);

  y = drawKeyTable(doc, autoTable, y, 'Checklist and sign-off', [
    ['Checklist', title],
    ['Technician', author.technicianName],
    ['Technician ID', author.technicianId || 'Not recorded'],
    ['Saved', formatWhen(snapshot.completedAt)],
    ['Items ticked', `${snapshot.completedItems} of ${snapshot.totalItems} (${percent}%)`],
    ['Outcome', complete ? 'Every item verified' : 'Items still outstanding'],
  ]);

  y = drawItemsTable(doc, autoTable, y, snapshot);

  y = drawAmberNote(doc, y, 'COMPLIANCE NOTE', complete
    ? 'Attach this checklist to a saved installation to request a Certificate of Conformity. HEVACRAZ reviews the checklist and the site photos before a certificate is issued.'
    : 'A Certificate of Conformity cannot be requested while lines remain outstanding. Tick the remaining items, save the checklist again and attach it to the installation record.');

  if (y > 236) {
    doc.addPage();
    y = 24;
  }

  drawSignatures(doc, y,
    'The technician confirms each ticked line was verified on site and that unticked lines remain outstanding. Keep a copy with the site logbook and submit the checklist through the Field Toolkit.',
    author.technicianName);

  drawFooters(doc, 'Generated by HEVACRAZ Field Toolkit');

  doc.save(`hevacraz-checklist-${snapshot.checklistType}-${snapshot.completedAt.slice(0, 10)}.pdf`);
}

function drawItemsTable(doc: jsPDF, autoTable: AutoTable, y: number, snapshot: InstallationChecklistSnapshot) {
  sectionHeading(doc, 'Verified items and outstanding lines', y);
  autoTable(doc, {
    startY: y + 5,
    theme: 'grid',
    head: [['Status', 'Category', 'Checklist item', 'Source']],
    body: snapshot.items.map(item => [
      item.checked ? 'Ticked' : 'Not ticked',
      item.category,
      item.text,
      item.source || 'HEVACRAZ checklist',
    ]),
    styles: {
      font: 'helvetica',
      fontSize: 8.5,
      cellPadding: 2.4,
      lineColor: BRAND.border,
      lineWidth: 0.2,
      textColor: BRAND.charcoal,
      valign: 'middle',
    },
    headStyles: { fillColor: BRAND.charcoal, textColor: [255, 255, 255], fontSize: 8, fontStyle: 'bold' },
    alternateRowStyles: { fillColor: BRAND.paper },
    columnStyles: {
      0: { cellWidth: 20, halign: 'center' },
      1: { cellWidth: 40, textColor: BRAND.stone },
      2: { cellWidth: 80 },
      3: { cellWidth: 24, fontSize: 7.5, textColor: BRAND.stone },
    },
    margin: { left: 20, right: 20 },
    didParseCell: (data: CellHookData) => {
      if (data.section !== 'body' || data.column.index !== 0) return;
      const item = snapshot.items[data.row.index];
      data.cell.styles.fontStyle = 'bold';
      data.cell.styles.textColor = item?.checked ? BRAND.sage : [159, 18, 57];
    },
  });
  return ((doc as DocWithTable).lastAutoTable?.finalY ?? y + 60) + 10;
}

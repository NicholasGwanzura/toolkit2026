import type { RefrigerantLog } from '@/types/index';
import { JobTypeLabels } from '@/types/index';
import {
  drawAmberNote,
  drawFooters,
  drawIdentityStrip,
  drawKeyTable,
  drawSignatures,
  formatWhen,
  loadLogo,
  newDocument,
} from '@/lib/pdf-brand';

/**
 * A branded field-service record: charcoal masthead, headline figures, detail tables,
 * compliance note, signature block and paged footer.
 */
export async function downloadGasLogPdf(log: RefrigerantLog) {
  const [{ jsPDF: JsPdf }, { default: autoTable }, logo] = await Promise.all([
    import('jspdf'),
    import('jspdf-autotable'),
    loadLogo(),
  ]);

  const doc = newDocument(JsPdf, {
    title: `HEVACRAZ gas log ${log.id}`,
    subject: 'Refrigerant service record',
    kicker: 'Field Service Log · Refrigerant record',
  }, logo, {
    label: 'LOG ID',
    value: log.id.slice(0, 18).toUpperCase(),
    lines: [formatWhen(log.timestamp), JobTypeLabels[log.jobType] ?? log.jobType],
  });

  let y = drawIdentityStrip(doc, 46, [
    {
      label: 'CLIENT / SITE',
      value: log.clientName,
      detail: log.location || 'Location not recorded',
      x: 20,
      maxWidth: 92,
    },
    { label: 'ACTION', value: log.actionType, detail: log.refrigerantType, x: 120 },
    { label: 'QUANTITY', value: `${log.amount} kg`, x: 158 },
  ]);

  y = drawKeyTable(doc, autoTable, y, 'Technician and service details', [
    ['Technician', log.technicianName],
    ['Technician ID', log.technicianId],
    ['Client', log.clientName],
    ['Work location', log.location || 'Not recorded'],
    ['Job type', JobTypeLabels[log.jobType] ?? log.jobType],
    ['Recorded', formatWhen(log.timestamp)],
    ['Planner job', log.plannerJobId ? log.plannerJobId.slice(0, 8).toUpperCase() : 'Not linked to a job'],
  ]);

  y = drawKeyTable(doc, autoTable, y, 'Refrigerant and supplier', [
    ['Action performed', log.actionType],
    ['Refrigerant', log.refrigerantType],
    ['Quantity recorded', `${log.amount} kg`],
    ['Approved supplier', log.approvedSupplierName || 'Unverified / not selected'],
    ['Supplier status', log.supplierVerified ? 'Verified approved supplier' : 'Unverified supplier'],
    ['Planner reference', log.plannerJobId ?? 'Not linked to a job'],
  ]);

  y = drawAmberNote(doc, y, 'COMPLIANCE NOTE',
    'This record supports SI 49 of 2023 and the Kigali Amendment. Only R-290, R-744 (CO2) and R-32 are permitted for new entries. Purchases from unapproved suppliers are not eligible for rewards points and are flagged in the National Ozone Unit compliance report.');

  if (y > 236) {
    doc.addPage();
    y = 24;
  }

  drawSignatures(doc, y,
    'The technician confirms the details above reflect the refrigerant work carried out at this site. Keep a copy for the site logbook and central registry audit trail.',
    log.technicianName);

  drawFooters(doc, 'Generated by HEVACRAZ Field Toolkit');

  doc.save(`hevacraz-gas-log-${log.id.slice(0, 8)}.pdf`);
}
